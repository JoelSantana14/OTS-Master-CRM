// Generate 877 realistic units for Jardim Vivência
export function generate877Units(): Unit[] {
  const units: Unit[] = [];
  let count = 0;
  const totalUnits = 877;

  // 38 Quadras, 20-26 lotes per quadra
  for (let q = 1; q <= 38 && count < totalUnits; q++) {
    const quadraStr = `Quadra ${String(q).padStart(2, '0')}`;
    const lotesInQuadra = q % 3 === 0 ? 25 : q % 2 === 0 ? 23 : 24;

    for (let l = 1; l <= lotesInQuadra && count < totalUnits; l++) {
      count++;
      const loteStr = `Lote ${String(l).padStart(2, '0')}`;
      const streetIndex = (q + l) % streets.length;
      const rua = streets[streetIndex];

      // Groups and pricing logic:
      // Grupo A (Faixa 1 MCMV): ~35% of units -> R$ 195.000 to R$ 208.000 (area 160m², constr 52.8m²)
      // Grupo B (Faixa 2 MCMV): ~45% of units -> R$ 215.000 to R$ 232.000 (area 180m², constr 58.5m²)
      // Grupo C (Faixa 3 MCMV/SBPE): ~20% of units -> R$ 242.000 to R$ 265.000 (area 220m², constr 68.0m²)
      let grupo: UnitGroup = 'Grupo B';
      let areaLote = 180;
      let areaConstruida = 58.5;
      let valorFinal = 219000;

      const mod = count % 10;
      if (mod < 4) {
        grupo = 'Grupo A';
        areaLote = 160 + (l % 4) * 5;
        areaConstruida = 52.8;
        valorFinal = 198000 + (l % 3) * 4000;
      } else if (mod < 8) {
        grupo = 'Grupo B';
        areaLote = 180 + (l % 5) * 8;
        areaConstruida = 58.5;
        valorFinal = 218000 + (l % 4) * 4500;
      } else {
        grupo = 'Grupo C';
        areaLote = 220 + (l % 4) * 12;
        areaConstruida = 68.2;
        valorFinal = 248000 + (l % 3) * 6000;
      }

      // Status distribution: 75% disponível, 10% reservado, 8% vendido, 7% análise
      let status: 'disponivel' | 'reservado' | 'vendido' | 'analise' = 'disponivel';
      let clienteNome: string | undefined;
      let corretorNome: string | undefined;
      let corretorId: string | undefined;
      let dataReserva: string | undefined;

      if (count === 4 || count === 18 || count === 42 || count === 75 || count === 104) {
        status = 'vendido';
        clienteNome = count === 4 ? 'Marcelo Henrique Silva' : 'Renata Souza Bittencourt';
        corretorNome = 'Lucas Mendes';
        corretorId = 'user-corretor-1';
      } else if (count === 12 || count === 29 || count === 58 || count === 88) {
        status = 'reservado';
        clienteNome = count === 12 ? 'Juliana Martins Castro' : 'Thiago Alcantara Dias';
        corretorNome = 'Camila Rocha';
        corretorId = 'user-corretor-2';
        dataReserva = '2026-08-19';
      } else if (count === 22 || count === 64 || count === 97) {
        status = 'analise';
        clienteNome = 'Rodrigo Barbosa Neves';
        corretorNome = 'Mariana Duarte';
        corretorId = 'user-corretor-4';
      }

      units.push({
        id: `unit-${count}`,
        quadra: quadraStr,
        lote: loteStr,
        rua,
        areaTerreno: areaLote,
        areaConstruida,
        valorFinal,
        grupo,
        status,
        valorAvaliacaoCef: valorFinal + 12000,
        clienteNome,
        corretorNome,
        corretorId,
        dataReserva,
      });
    }
  }

  return units;
}

